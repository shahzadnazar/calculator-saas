/**
 * assert:embed-isolation (R7D1.1) — a FAILING architectural gate for the public
 * calculator embeds. Unlike `report:embed-css` (informational transfer report),
 * this exits non-zero when the per-slug code-split is violated. It has no byte
 * budget — only the invariant that a public embed carries NO unrelated calculator.
 *
 * Run AFTER `npm run build`. Checks every generated calculator embed route in dist
 * plus the source guards that make a regression structurally impossible.
 *
 * FAILS when:
 *   - a public embed's CSS contains scoped rules for a calculator `data-astro-cid`
 *     that is not rendered on that page (unrelated calculator-scoped CSS / ownership);
 *   - the legacy dynamic renderer returns: `src/components/IslandBySlug.astro` or
 *     `src/pages/embed/[category]/[slug].astro` exists;
 *   - a generated embed page uses a component map, `import.meta.glob`, a runtime
 *     dynamic import, a client-side component loader (`<script>`), or more than one
 *     calculator-component import.
 *
 * Allowed shared styling: the EmbedPageShell / EmbedLayout shell cid (it IS rendered
 * on every embed), global design-system CSS and shared result CSS (linked, not
 * scoped to an unrelated calculator).
 */
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';

const DIST = 'dist';
const PAGES = 'src/pages/embed';
const problems = [];

/* ---- 1. legacy dynamic renderer must be gone ---------------------------- */
for (const p of ['src/components/IslandBySlug.astro', 'src/pages/embed/[category]/[slug].astro']) {
  if (existsSync(resolve(p))) problems.push(`legacy dynamic renderer still present: ${p}`);
}

/* ---- 2. generated-page source guards ------------------------------------ */
const GEN_MARKER = 'AUTO-GENERATED by scripts/gen-embed-pages.mjs';
const RESERVED = new Set(['[category]', 'reference', 'gallery.astro', 'index.astro']);
function generatedPages() {
  const out = [];
  for (const entry of readdirSync(PAGES)) {
    if (RESERVED.has(entry)) continue;
    let files;
    try {
      files = readdirSync(resolve(PAGES, entry));
    } catch {
      continue;
    }
    for (const f of files) {
      if (!f.endsWith('.astro')) continue;
      const p = resolve(PAGES, entry, f);
      const src = readFileSync(p, 'utf8');
      if (src.includes(GEN_MARKER)) out.push({ rel: `embed/${entry}/${f}`, src });
    }
  }
  return out;
}
const generated = generatedPages();
for (const { rel, src } of generated) {
  if (/import\.meta\.glob/.test(src)) problems.push(`${rel}: uses import.meta.glob`);
  if (/ISLANDS\[|IslandBySlug/.test(src)) problems.push(`${rel}: uses a component map / IslandBySlug`);
  if (/await import\(/.test(src)) problems.push(`${rel}: uses a runtime dynamic import`);
  if (/<script/.test(src)) problems.push(`${rel}: contains a <script> (client-side component loader not allowed on the page)`);
  const imports = [...src.matchAll(/import Island from '[^']+';/g)].length;
  if (imports !== 1) problems.push(`${rel}: has ${imports} calculator-component imports (must be exactly 1)`);
}

/* ---- 3. built-output isolation: 0 unrelated calculator-scoped CSS -------- */
function embedRoutes() {
  const out = [];
  const base = resolve(DIST, 'embed');
  for (const entry of readdirSync(base)) {
    if (entry === 'reference' || entry.endsWith('.html')) continue; // reference/[slug] + gallery/index are separate
    let files;
    try {
      files = readdirSync(resolve(base, entry));
    } catch {
      continue;
    }
    for (const f of files) if (f.endsWith('.html')) out.push(`embed/${entry}/${f}`);
  }
  return out;
}

function unrelatedScopedCids(htmlPath) {
  const html = readFileSync(resolve(DIST, htmlPath), 'utf8');
  // Collect all CSS: inline <style> blocks + linked stylesheets.
  const inline = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join('\n');
  let linked = '';
  for (const m of html.matchAll(/<link[^>]+rel="stylesheet"[^>]+href="([^"]+)"/g)) {
    const p = resolve(DIST, m[1].replace(/^\//, ''));
    if (existsSync(p)) linked += readFileSync(p, 'utf8');
  }
  const css = `${inline}\n${linked}`;
  // Cids present on RENDERED elements (strip <style> first so selectors don't count).
  const rendered = new Set(
    [...html.replace(/<style[^>]*>[\s\S]*?<\/style>/g, '').matchAll(/data-astro-cid-([a-z0-9]+)/g)].map((m) => m[1]),
  );
  // Cids that own scoped CSS rules.
  const scoped = new Set([...css.matchAll(/data-astro-cid-([a-z0-9]+)/g)].map((m) => m[1]));
  return [...scoped].filter((cid) => !rendered.has(cid));
}

const routes = embedRoutes();
// Derived from the generated SOURCE pages (themselves reconciled against the registry by
// `assert:embed-pages-current`), not a literal — so adding a calculator never needs this file
// edited, while a build that silently drops or duplicates an embed still fails here.
if (routes.length !== generated.length) {
  problems.push(`expected ${generated.length} calculator embed routes in dist, found ${routes.length}`);
}
for (const route of routes) {
  const orphans = unrelatedScopedCids(route);
  if (orphans.length) problems.push(`${route}: unrelated calculator-scoped CSS for cid(s) ${orphans.join(', ')}`);
}

/* ---- verdict ------------------------------------------------------------ */
if (problems.length) {
  console.error(`✗ embed isolation VIOLATED (${problems.length}):\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
console.log(`✓ embed isolation holds — ${routes.length} calculator embeds, each with 0 unrelated calculator-scoped CSS.`);
