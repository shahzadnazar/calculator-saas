/**
 * Generate the per-slug PUBLIC EMBED pages (R7D1 · source-of-truth hardened R7D1.1).
 *
 * Reads two authorities and writes one static Astro page per LIVE calculator under
 *   src/pages/embed/<category>/<slug>.astro
 * each with a LITERAL static import of exactly one island + the shared
 * EmbedPageShell. That literal import is what lets Astro emit only that island's
 * scoped CSS (the old dynamic `IslandBySlug` map defeated static analysis).
 *
 * SOURCE OF TRUTH (R7D1.1):
 *   - The calculator REGISTRY (src/data/calculators.ts) owns which calculators are
 *     live and their category → so the generated ROUTE PATHS are derived from the
 *     registry, not from the manifest.
 *   - The embed MANIFEST (src/data/embed-components.json) owns ONLY component
 *     identity: `slug → { componentPath, props? }`. It carries no category/title/
 *     status (no duplicated registry projection).
 * The generator fails loudly if the two disagree (a live calculator with no
 * manifest entry, or a manifest entry that is not a live calculator).
 *
 * Deterministic across operating systems: slugs sorted, forward-slash import
 * paths, LF newlines, single trailing newline, sorted prop keys.
 *
 * Usage:
 *   node scripts/gen-embed-pages.mjs                 # write all pages
 *   node scripts/gen-embed-pages.mjs --only a,b,c    # write only these slugs (proof gate)
 *   node scripts/gen-embed-pages.mjs --check         # drift gate: fail if on-disk output is stale/missing/orphaned
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';

const MAP_PATH = 'src/data/embed-components.json';
const REGISTRY_PATH = 'src/data/calculators.ts';
const PAGES_DIR = 'src/pages/embed';
const GEN_MARKER = 'AUTO-GENERATED by scripts/gen-embed-pages.mjs';
// Non-generated routes that also live under src/pages/embed/ and must be left alone.
const RESERVED = new Set(['[category]', 'reference', 'gallery.astro', 'index.astro']);

const argv = process.argv.slice(2);
const check = argv.includes('--check');
const onlyIdx = argv.indexOf('--only');
const only = onlyIdx >= 0 && argv[onlyIdx + 1] ? new Set(argv[onlyIdx + 1].split(',').map((s) => s.trim())) : null;

/* ---- authorities -------------------------------------------------------- */

const map = JSON.parse(readFileSync(MAP_PATH, 'utf8'));
const slugs = Object.keys(map).sort();

/**
 * Live slug → category, parsed from the registry (the authority). Calculator
 * entries contain no nested `{}` (only `[]` arrays), so splitting the CALCULATORS
 * array on `}` yields one object chunk each; fields are read order-independently.
 */
function parseRegistryCategories() {
  const src = readFileSync(REGISTRY_PATH, 'utf8');
  const arr = src.match(/export const CALCULATORS[^=]*=\s*\[([\s\S]*?)\n\](?:\s*as const)?;/);
  if (!arr) fail(`could not locate the CALCULATORS array in ${REGISTRY_PATH}`);
  const live = {};
  for (const chunk of arr[1].split('}')) {
    const slug = chunk.match(/slug:\s*'([^']+)'/)?.[1];
    const category = chunk.match(/category:\s*'([^']+)'/)?.[1];
    const status = chunk.match(/status:\s*'([^']+)'/)?.[1];
    if (slug && category && status === 'live') live[slug] = category;
  }
  return live;
}
const registry = parseRegistryCategories();

function categoryOf(slug) {
  const c = registry[slug];
  if (!c) fail(`"${slug}" is in the manifest but is not a LIVE calculator in the registry`);
  return c;
}

function fail(msg) {
  console.error(`✗ embed-pages: ${msg}`);
  process.exit(1);
}

/* ---- validation of the manifest ↔ registry ------------------------------ */
function validate() {
  const seenRoutes = new Set();
  for (const slug of slugs) {
    const def = map[slug];
    if (!def || typeof def !== 'object') fail(`manifest entry for "${slug}" is not an object`);
    if (!def.componentPath) fail(`"${slug}" has no componentPath`);
    if ('category' in def) fail(`"${slug}" must not carry a category — the registry is the route authority`);
    const disk = def.componentPath.replace(/^@components\//, 'src/components/');
    if (!existsSync(resolve(disk))) fail(`"${slug}" componentPath does not exist: ${def.componentPath}`);
    if (def.props !== undefined) {
      for (const [k, v] of Object.entries(def.props)) {
        if (!['string', 'number', 'boolean'].includes(typeof v)) fail(`"${slug}" prop "${k}" is not serializable (${typeof v})`);
      }
    }
    const route = `${categoryOf(slug)}/${slug}`;
    if (seenRoutes.has(route)) fail(`duplicate embed route: ${route}`);
    seenRoutes.add(route);
  }
  // Every LIVE calculator must have a manifest entry.
  for (const slug of Object.keys(registry)) {
    if (!map[slug]) fail(`live calculator "${slug}" has no embed manifest entry (${MAP_PATH})`);
  }
}

/* ---- deterministic page content ----------------------------------------- */
function serializeProps(props) {
  if (!props) return '';
  const parts = Object.keys(props)
    .sort()
    .map((k) => (typeof props[k] === 'string' ? `${k}=${JSON.stringify(props[k])}` : `${k}={${JSON.stringify(props[k])}}`));
  return parts.length ? ` ${parts.join(' ')}` : '';
}

function pageContent(slug) {
  const { componentPath, props } = map[slug];
  const category = categoryOf(slug);
  return [
    '---',
    `// ${GEN_MARKER} — DO NOT EDIT BY HAND.`,
    '// Source: src/data/embed-components.json (component identity) + the calculator',
    '// registry (@data/calculators — route authority). Regenerate: npm run gen:embed-pages',
    '// · Drift check: npm run assert:embed-pages-current',
    "import EmbedPageShell from '@layouts/EmbedPageShell.astro';",
    `import Island from '${componentPath}';`,
    "import { getCalculator } from '@data/calculators';",
    '',
    `const calculator = getCalculator('${category}', '${slug}')!;`,
    '---',
    '',
    '<EmbedPageShell calculator={calculator}>',
    `  <Island${serializeProps(props)} />`,
    '</EmbedPageShell>',
    '',
  ].join('\n');
}

function pagePath(slug) {
  return resolve(PAGES_DIR, categoryOf(slug), `${slug}.astro`);
}

/* ---- existing generated files (by marker) ------------------------------- */
function listGenerated() {
  const found = [];
  for (const entry of readdirSync(PAGES_DIR)) {
    if (RESERVED.has(entry)) continue;
    let files;
    try {
      files = readdirSync(resolve(PAGES_DIR, entry));
    } catch {
      continue;
    }
    for (const file of files) {
      if (!file.endsWith('.astro')) continue;
      const p = resolve(PAGES_DIR, entry, file);
      if (readFileSync(p, 'utf8').includes(GEN_MARKER)) found.push({ slug: file.replace(/\.astro$/, ''), category: entry });
    }
  }
  return found;
}

/* ---- modes -------------------------------------------------------------- */
validate();

if (check) {
  const problems = [];
  for (const slug of slugs) {
    const p = pagePath(slug);
    if (!existsSync(p)) problems.push(`missing: embed/${categoryOf(slug)}/${slug}.astro`);
    else if (readFileSync(p, 'utf8') !== pageContent(slug)) problems.push(`stale:   embed/${categoryOf(slug)}/${slug}.astro`);
  }
  const known = new Set(slugs.map((s) => `${categoryOf(s)}/${s}`));
  for (const g of listGenerated()) {
    if (!known.has(`${g.category}/${g.slug}`)) problems.push(`orphan:  embed/${g.category}/${g.slug}.astro (not in ${MAP_PATH})`);
  }
  if (problems.length) {
    console.error(`✗ embed pages are out of date — run \`npm run gen:embed-pages\`:\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`✓ all ${slugs.length} generated embed pages are current.`);
  process.exit(0);
}

if (only) {
  const unknown = [...only].filter((s) => !map[s]);
  if (unknown.length) fail(`--only names unknown slug(s): ${unknown.join(', ')}`);
}
const targets = only ? slugs.filter((s) => only.has(s)) : slugs;
let written = 0;
for (const slug of targets) {
  const p = pagePath(slug);
  mkdirSync(dirname(p), { recursive: true });
  const content = pageContent(slug);
  if (!existsSync(p) || readFileSync(p, 'utf8') !== content) {
    writeFileSync(p, content);
    written += 1;
  }
}
console.log(`✓ generated ${targets.length} embed page(s) (${written} written/changed) under ${PAGES_DIR}/.`);
